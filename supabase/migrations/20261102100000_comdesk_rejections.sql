CREATE TABLE IF NOT EXISTS provenance.comdesk_rejections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL CHECK (source = 'コムデスク'),
    import_batch_id text NOT NULL CHECK (import_batch_id ~ '^[0-9a-f]{64}$'),
    row_number integer NOT NULL CHECK (row_number >= 2),
    reason_code text NOT NULL CHECK (reason_code IN (
        'INVALID_UUID_MAPPING',
        'MISSING_CASE_ID',
        'MISSING_PROJECT_SCOPE',
        'DUPLICATE_CASE_IN_SCOPE',
        'INVALID_IDENTIFIER_FORMAT',
        'INVALID_RECORD_FORMAT',
        'MISSING_CLINIC_NAME',
        'NO_EXISTING_CLINIC_MATCH'
    )),
    reason_detail text NOT NULL,
    raw_record_json jsonb NOT NULL,
    normalized_record_json jsonb,
    mapping_snapshot_json jsonb NOT NULL,
    project_scope_id text,
    source_hash text NOT NULL CHECK (source_hash ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'REVIEWED', 'REJECTED', 'RESOLVED')),
    reviewed_by text,
    reviewed_at timestamptz,
    reviewed_note text,
    UNIQUE (import_batch_id, row_number, reason_code, source_hash)
);

CREATE INDEX IF NOT EXISTS comdesk_rejections_status_created_idx
    ON provenance.comdesk_rejections(status, created_at);

CREATE INDEX IF NOT EXISTS comdesk_rejections_batch_row_idx
    ON provenance.comdesk_rejections(import_batch_id, row_number);

REVOKE ALL ON TABLE provenance.comdesk_rejections FROM PUBLIC, anon, authenticated;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'clinic_comdesk_import_writer') THEN
        GRANT INSERT ON TABLE provenance.comdesk_rejections TO clinic_comdesk_import_writer;
        GRANT USAGE ON SEQUENCE provenance.comdesk_rejections_id_seq
            TO clinic_comdesk_import_writer;
    END IF;
END
$$;
