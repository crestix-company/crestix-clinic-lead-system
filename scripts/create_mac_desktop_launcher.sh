#!/bin/bash
# macOS: create or update the Desktop launcher "Clinic Lead System.command".
#
# This is the Mac counterpart of scripts/create_windows_desktop_shortcut.ps1.
# The generated launcher carries no credential values and no arguments; it only
# cd's into the Runtime clone and execs update_and_launch_mac.sh there.
#
# The target Runtime directory and the Desktop directory are both resolved at
# creation time via $HOME / explicit overrides, never a hardcoded username, so
# this script works unmodified for any user account.
#
# Usage:
#   scripts/create_mac_desktop_launcher.sh [runtime_dir]
#
# Overrides (mainly for tests):
#   CLINIC_RUNTIME_DIR  - runtime clone directory (default: $HOME/ClinicLeadRuntime)
#   CLINIC_DESKTOP_DIR  - Desktop directory (default: $HOME/Desktop)
set -euo pipefail

error_exit() {
    echo "[ERROR] $1" >&2
    exit 1
}

RUNTIME_DIR="${1:-${CLINIC_RUNTIME_DIR:-$HOME/ClinicLeadRuntime}}"
DESKTOP_DIR="${CLINIC_DESKTOP_DIR:-$HOME/Desktop}"
LAUNCHER_NAME="Clinic Lead System.command"

RUNTIME_UPDATER="$RUNTIME_DIR/scripts/update_and_launch_mac.sh"
if [ ! -f "$RUNTIME_UPDATER" ]; then
    error_exit "Runtime setupが完了していません: $RUNTIME_UPDATER が見つかりません。先に scripts/setup_mac_one_click.sh を実行してください。"
fi

mkdir -p "$DESKTOP_DIR"
LAUNCHER_PATH="$DESKTOP_DIR/$LAUNCHER_NAME"

if [ -d "$LAUNCHER_PATH" ]; then
    error_exit "同名のフォルダが既に存在します: $LAUNCHER_PATH"
fi

cat > "$LAUNCHER_PATH" <<LAUNCHER_SCRIPT
#!/bin/bash
# Auto-generated by scripts/create_mac_desktop_launcher.sh. Do not edit by hand;
# re-run the creator instead. Carries no credential values and no arguments.
set -euo pipefail
exec "$RUNTIME_DIR/scripts/update_and_launch_mac.sh"
LAUNCHER_SCRIPT

chmod +x "$LAUNCHER_PATH"

echo "Desktop launcher ready: $LAUNCHER_PATH"
echo "  Runtime: $RUNTIME_DIR"
